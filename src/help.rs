//! The help menu (H / F1, or the quit menu): topics, each a few pages. The controls name the device you're on
//! (on a handheld, the pad buttons as remapped in binds.rs).
use crate::binds::{label, PadAct};
use crate::skills::Class;

/// The topics, in menu order.
pub const TOPICS: [&str; 13] = [
    "QUICK START",
    "CONTROLS",
    "YOUR GOAL AND THE QUEST LOG",
    "FINDING YOUR WAY",
    "SKILLS AND LEVELS",
    "POTIONS, FOOD AND YOUR BELT",
    "GEAR, GEMS AND SELLING",
    "TOWNS AND PEOPLE",
    "SIDE QUESTS AND SECRETS",
    "YOUR HERO",
    "DYING, NIGHTMARE AND THE ENDGAME",
    "SAVING AND QUITTING",
    "PLAYING ONLINE",
];

/// The pages of a topic.
pub fn topic(i: usize, handheld: bool, class: Class) -> Vec<String> {
    let k = |pad: String, keys: &str| if handheld { pad } else { keys.to_string() };
    let main = k(format!("{} (OR PUSH THE RIGHT STICK)", label(PadAct::Primary)), "F, OR LEFT-CLICK A MONSTER");
    let second = k(label(PadAct::Secondary), "SPACE, OR RIGHT-CLICK");
    let run = k(label(PadAct::Run), "R");
    let tree = k(label(PadAct::SkillTree), "K");
    let next = k(label(PadAct::NextSkill), "1-4");
    let hp = k(label(PadAct::HealPotion), "Q");
    let mp = k(label(PadAct::ManaPotion), "E");
    let back = k(label(PadAct::Back), "ESC");
    let bag = k("START".into(), "I");
    let map = k("TAP SELECT".into(), "TAB OR M");
    let eat = k("HOLD SELECT".into(), "G");
    let talk = k(format!("{} NEXT TO THEM", label(PadAct::Primary)), "F OR SPACE NEXT TO THEM, OR CLICK THEM");
    let quit = k("SELECT + START".into(), "ESC");
    let help = k("SELECT + START, THEN HELP".into(), "H OR F1");
    let pages: Vec<String> = match i {
        0 => crate::story::guide(handheld),
        1 => {
            let mut v = vec![
                format!("MOVE: {}. MAIN SKILL: {main}. SECOND SKILL: {second}. SWITCH THE SECOND SKILL: {next}.", k("LEFT STICK OR D-PAD".into(), "WASD, ARROWS, OR HOLD THE LEFT MOUSE BUTTON ON THE FLOOR")),
                format!("HEALING POTION: {hp}. MANA POTION: {mp}. EAT (THE VAMPIRE: DRINK): {eat}. RUN OR WALK: {run}."),
                format!("BAG: {bag}. SKILL TREE: {tree}. MAP: {map}. TALK: {talk}. CLOSE THINGS: {back}. QUIT MENU: {quit}. HELP: {help}."),
            ];
            if handheld {
                v.push("EVERY BUTTON BUT START, SELECT AND THE D-PAD CAN BE CHANGED: HELP > GAMEPAD BUTTONS.".into());
            } else {
                v.push("A GAMEPAD WORKS TOO: LEFT STICK MOVES, A AND X ARE YOUR SKILLS, START OPENS THE BAG, TAP SELECT FOR THE MAP. CHANGE ITS BUTTONS IN HELP > GAMEPAD BUTTONS.".into());
            }
            v
        }
        2 => vec![
            "WHAT TO DO NEXT IS ALWAYS WRITTEN AT THE TOP LEFT, UNDER THE AREA'S NAME: THE QUEST LOG. ANY SIDE QUESTS YOU'VE TAKEN ARE LISTED UNDER IT.".into(),
            "EVERY ACT GOES THE SAME WAY. TALK TO THE ACT'S STORYTELLER IN TOWN: A MARKER HANGS OVER ANYONE WITH NEWS. THEY SEND YOU AFTER THE ACT'S THREE HERALDS, EACH AT THE BOTTOM OF ITS OWN DUNGEON.".into(),
            "EACH HERALD DROPS A RELIC (A SEAL, A RUNE, A KEY...) THAT MAKES YOU STRONGER. WITH ALL THREE, GO BACK TO THE STORYTELLER: THE WAY TO THE ACT'S LAST BOSS OPENS. BEAT IT, AND THE WAY TO THE NEXT ACT OPENS.".into(),
            "STUCK? READ THE QUEST LOG, TALK TO THE STORYTELLER AGAIN, AND LOOK AT THE MAP FOR DOORS AND ROADS YOU HAVEN'T TAKEN.".into(),
        ],
        3 => vec![
            format!("THE MAP ({map}) SHOWS WHAT YOU'VE EXPLORED, THE ROADS TO OTHER AREAS, AND THE DOORS DOWN INTO DUNGEONS. EACH ACT IS A TOWN AND A RING OF AREAS AROUND IT."),
            "WAYPOINTS ARE GLOWING STONES, ONE IN EACH TOWN AND IN MANY AREAS. TOUCH ONE AND IT'S YOURS: STEP ON ANY WAYPOINT LATER TO TRAVEL TO IT.".into(),
            format!("ROADS OFF AN AREA END IN A GLOWING GATE, NAMED FOR WHERE IT LEADS: WALK INTO IT. A MINIMAP SITS AT THE TOP RIGHT. A TOWN PORTAL SCROLL ({}) OPENS A WAY TO TOWN; THE PORTAL IN TOWN BRINGS YOU BACK.", k("FROM THE BAG".into(), "T, OR FROM THE BAG")),
            "DUNGEONS GO DOWN FLOOR BY FLOOR; THE STAIRS DOWN ARE FAR FROM WHERE YOU COME IN. THE BOSS WAITS ON THE LAST FLOOR, AND WHEN IT FALLS A WAY HOME OPENS NEXT TO IT.".into(),
            "THE MAPS ARE MADE AFRESH FOR EACH HERO, SO NO TWO PLAYTHROUGHS LOOK THE SAME.".into(),
        ],
        4 => vec![
            format!("EVERY LEVEL GIVES A SKILL POINT (AND SOME QUESTS GIVE MORE). SPEND THEM IN THE SKILL TREE ({tree}). A SKILL NEEDS THE ONE ABOVE IT FIRST, AND MORE POINTS MAKE IT STRONGER."),
            format!("YOUR MAIN SKILL IS ON {main}; YOUR SECOND SKILL ON {second}. {next} PICKS WHICH SKILL SITS ON THE SECOND BUTTON."),
            format!("RUNNING ({run} SWITCHES IT) IS FASTER BUT USES UP STAMINA; RUN OUT AND YOU WALK UNTIL IT COMES BACK. HUNGER DRAINS FASTER WHILE YOU RUN."),
        ],
        5 => vec![
            format!("YOUR POTION BELT HOLDS 6 POTIONS TO START (HEALING AND MANA TOGETHER): {hp} DRINKS A HEALING ONE, {mp} A MANA ONE. WITH THE BELT FULL, SPARES GO IN YOUR BAG; PICK ONE THERE AND CONFIRM TO MOVE IT TO THE BELT."),
            format!("FOOD GOES IN YOUR FOOD BAG (3 MEALS TO START). EAT WITH {eat} WHEN THE FOOD BAR RUNS LOW: IT PICKS THE MEAL THAT FILLS YOU BEST. STARVING SLOWLY HURTS. YOU DON'T GET HUNGRY IN TOWN."),
            "THE VAMPIRE DOESN'T EAT: SHE FEEDS ON BLOOD AS SHE FIGHTS. BLOOD PAST SATED GOES IN HER BLOOD VIAL, AND SHE DRINKS FROM IT WITH THE EAT BUTTON.".into(),
            "SIX SIDE QUESTS (ONE IN EACH OF ACTS 1-6) GIVE A BIGGER BELT OR A BIGGER FOOD BAG (OR VIAL) ON TOP OF THEIR REWARD. MERCHANTS IN EVERY TOWN SELL POTIONS AND FOOD.".into(),
        ],
        6 => vec![
            format!("WALK OVER GEAR TO PICK IT UP. OPEN YOUR BAG ({bag}): CONFIRM ON AN ITEM TO WEAR IT, AND THE ITEM YOU HAD GOES BACK IN THE BAG. AN ITEM TINTED RED NEEDS A HIGHER LEVEL."),
            "COLOURS: WHITE IS PLAIN, BLUE MAGIC, YELLOW RARE, GREEN A SET PIECE (MORE BONUSES THE MORE OF THE SET YOU WEAR), GOLD UNIQUE, ORANGE ANCIENT. BOSSES DROP THEIR OWN UNIQUES.".into(),
            "GEMS GO IN SOCKETS: PICK THE GEM, THEN THE ITEM. THE JEWELER IN TOWN JOINS THREE ALIKE INTO A BETTER ONE, ADDS SOCKETS, AND TAKES GEMS BACK OUT.".into(),
            format!("IN TOWN, {second} ON AN ITEM IN YOUR BAG SELLS IT. THE STASH CHEST IN TOWN KEEPS WHAT YOUR BAG CAN'T HOLD."),
            format!("PICK AN ITEM IN THE BAG AND IT SAYS WHAT WEARING IT WOULD CHANGE: GREEN BETTER, RED WORSE. {} SORTS THE BAG. {}", k(label(PadAct::NextSkill), "R1 (OR THE SORT BUTTON)"), k(String::new(), "HOLD ALT TO SEE THE NAMES OF EVERYTHING ON THE GROUND.")),
        ],
        7 => vec![
            format!("EVERY TOWN IS SAFE: NO MONSTERS, AND NO HUNGER. TALK TO PEOPLE ({talk})."),
            "THE MERCHANT SELLS POTIONS, FOOD AND GEAR, AND BUYS YOURS. THE HEALER MENDS YOU FOR FREE. THE JEWELER WORKS YOUR GEMS AND SOCKETS. THE STORYTELLER MOVES THE ACT ALONG.".into(),
            "MANY TOWNSFOLK HAVE SIDE QUESTS: ASK THEM. EVERY TOWN ALSO HAS A WAYPOINT, A STASH CHEST, AND THE REKINDLING BRAZIER, WHICH BRINGS AN ACT'S BOSSES BACK FOR MORE LOOT ONCE THEY'RE BEATEN.".into(),
        ],
        8 => vec![
            "SIDE QUESTS: TALK TO EVERYONE. THEY GIVE SKILL POINTS, LIFE, GEAR, SOCKETS AND MORE. YOUR OPEN ONES ARE LISTED UNDER THE QUEST LOG.".into(),
            "OUT IN THE AREAS: SHRINES (TOUCH ONE FOR A BLESSING), NAMED MONSTERS WITH THEIR OWN UNIQUES, LOST LORE PAGES (FIND ALL OF AN ACT'S FOR MORE EXPERIENCE), HIDDEN DUNGEONS, AND SMALL ERRANDS THAT CHANGE EVERY PLAYTHROUGH.".into(),
            "THE BESTIARY COUNTS YOUR KILLS OF EACH MONSTER, AND YOU HIT THAT KIND HARDER AS IT GROWS. LATER: A RIVAL ADVENTURER, MERCHANT CARAVANS, AND THE ARENA.".into(),
        ],
        9 => class_tips(class),
        10 => vec![
            format!("IF YOU FALL, {} AND YOU WAKE IN TOWN. YOU LOSE A TENTH OF YOUR GOLD; YOUR GEAR AND YOUR PROGRESS ARE SAFE. A HARDCORE HERO (CHOSEN WHEN YOU NAME THEM) HAS ONE LIFE: IF THEY FALL, THEY STAY IN THE HERO LIST AS A MEMORIAL AND CAN'T BE PLAYED AGAIN. WANT A HARDER, RICHER GAME? SET PLAYERS (OPTIONS, OR THIS MENU) UP TO 8: MONSTERS GET TOUGHER AND MORE NUMEROUS, AND GIVE MORE EXPERIENCE AND LOOT.", k("PRESS START".into(), "PRESS ENTER")),
            "BEAT THE LAST ACT AND NIGHTMARE OPENS, THEN HELL: THE SAME WORLD, MADE HARDER, WITH BETTER LOOT. YOUR HERO, SKILLS AND GEAR CARRY ON; THE QUESTS START OVER.".into(),
            "THE ENDGAME: THE REKINDLING BRAZIER BRINGS BOSSES BACK, THE RIFTWARDEN OPENS ASH RIFTS, PAST LEVEL 50 EMBERS MAKE YOU STRONGER STILL, AND ANCIENT ITEMS CARRY SPECIAL POWERS.".into(),
        ],
        11 => vec![
            "YOUR HERO IS SAVED BY ITSELF: IN TOWN, WHEN A BOSS FALLS, AND WHEN YOU QUIT. EACH HERO HAS THEIR OWN SAVE; PICK ONE FROM THE HERO LIST.".into(),
            format!("{quit} ASKS WHETHER TO KEEP PLAYING, GO BACK TO THE HEROES, OR QUIT THE GAME. NOTHING IS LOST EITHER WAY."),
        ],
        _ => vec![
            "PLAY ONLINE (ON THE TITLE SCREEN): ONE PLAYER HOSTS, UP TO SEVEN FRIENDS JOIN. EVERYONE PLAYS IN THE HOST'S WORLD, AND THE MONSTERS GROW TOUGHER AND MORE NUMEROUS FOR EACH HERO.".into(),
            "TO HOST: PICK A PORT (4747 IF UNSURE) AND, IF YOU LIKE, A PASSWORD, THEN YOUR HERO. TELL YOUR FRIENDS YOUR ADDRESS AND THE HOST KEY SHOWN. FROM OUTSIDE YOUR HOME, OPEN THAT PORT ON YOUR ROUTER.".into(),
            "TO JOIN: TYPE THE HOST'S ADDRESS AND PASSWORD. THE FIRST TIME, THE GAME SHOWS THE HOST'S KEY: JOIN ONLY IF IT MATCHES THE ONE ON YOUR FRIEND'S SCREEN. IF IT EVER CHANGES, THE GAME WON'T JOIN.".into(),
            "THE HOST'S QUESTS ARE THE ONES IN PLAY. YOUR HERO KEEPS THE LEVELS, GOLD, GEAR AND SKILLS IT EARNS THERE; YOUR OWN QUESTS AND WAYPOINTS STAY AS THEY WERE. ESC LEAVES THE GAME.".into(),
            "ENTER OPENS A CHAT LINE: TYPE, THEN ENTER TO SEND (ESC TO CANCEL). EVERYONE GETS THEIR OWN LOOT, AND SHARES THE EXPERIENCE FROM KILLS NEARBY. HARDCORE HEROES PLAY ONLY IN HARDCORE GAMES. EVERYTHING SENT IS ENCRYPTED.".into(),
        ],
    };
    pages
}

/// A few words on how your class plays.
fn class_tips(class: Class) -> Vec<String> {
    let t: &[&str] = match class {
        Class::Sorceress => &[
            "THE SORCERESS FIGHTS WITH FIRE. HER SPELLS SET FOES BURNING, AND BURNING FOES KEEP TAKING DAMAGE.",
            "SHE RUNS ON MANA. OUT OF MANA, HER EMBER BOLT STILL FIRES FOR FREE, SO SHE IS NEVER HELPLESS. KEEP MANA POTIONS FOR THE BIG FIGHTS.",
        ],
        Class::Vampire => &[
            "THE VAMPIRE'S DAMAGE IS BLOOD. ALMOST EVERYTHING SHE DOES STEALS LIFE, BUT THE BLOODLESS (SKELETONS, WRAITHS AND THEIR KIN) CAN'T BE DRAINED.",
            "SHE DOESN'T EAT: SHE FEEDS ON BLOOD AS SHE FIGHTS. BLOOD PAST SATED FILLS HER BLOOD VIAL; DRINK FROM IT WITH THE EAT BUTTON WHEN YOU'RE THIRSTY.",
        ],
        Class::Inventor => &[
            "THE INVENTOR RUNS ON HEAT, NOT MANA: FIRING HEATS HER UP, COOLING DOWN BRINGS IT BACK. ABOVE 70% HEAT SHE HITS HARDER.",
            "HIT ZERO AND SHE OVERHEATS: HER GUNS LOCK FOR TWO SECONDS. THE MANA POTION BUTTON VENTS STEAM, DUMPING ALL HER HEAT AND BLASTING FOES BACK.",
            "HER RAPIER COSTS NO HEAT AT ALL: PUT IT ON YOUR SECOND BUTTON FOR FOES THAT GET TOO CLOSE, AND FOR WHEN HER GUNS OVERHEAT.",
        ],
        Class::Valkyrie => &[
            "THE VALKYRIE FIGHTS UP CLOSE WITH A FROST SPEAR. FROST BUILDS ON A FOE UNTIL IT FREEZES SOLID, AND FROZEN FOES SHE KILLS SHATTER.",
            "SHE RUNS ON VALOR: IT STARTS EMPTY, HER HITS AND THE BLOWS SHE TAKES FILL IT, AND HER SKILLS SPEND IT. AT FULL VALOR SHE HITS HARDER.",
        ],
        Class::Berserker => &[
            "THE BERSERKER SWINGS A GREAT AXE WITH HER DIRE WOLF AT HER SIDE. NO MAGIC: SHE RUNS ON RAGE, FILLED BY THE BLOWS SHE TAKES AND THE FOES SHE KILLS.",
            "THE LOWER HER LIFE, THE HARDER SHE HITS. CLEAVE IS FREE, SO SHE CAN ALWAYS FIGHT. HER AXE MAKES FOES BLEED.",
        ],
        Class::Reaper => &[
            "THE REAPER RUNS ON SOULS: EVERY FOE THAT DIES NEAR HER FILLS HER LANTERN, AND HER BIGGER SKILLS SPEND THEM. HER REAPING SCYTHE IS FREE.",
            "HER SCYTHE'S RUNES LIGHT ONE BY ONE AS SHE KEEPS HITTING THE SAME PREY. AT SEVEN, HER NEXT SWEEP DOES TRIPLE DAMAGE.",
        ],
        Class::Druid => &[
            "THE DRUID LETS HER CREATURES FIGHT (RATS, A MOSS WOLF, THE THORN WARDEN) WHILE SHE SPREADS POISON AND MENDS HER OWN.",
            "BESIDES MANA SHE KEEPS A BALANCE BETWEEN DECAY AND BLOOM: PLAGUE SKILLS PUSH IT ONE WAY, GROWTH SKILLS THE OTHER, AND EACH SIDE MAKES THE OTHER'S SKILLS STRONGER.",
        ],
        Class::Inquisitor => &[
            "THE INQUISITOR SWINGS A CENSER ON A LONG CHAIN: SHE HITS FROM A FEW STEPS AWAY. EVERY SKILL IS A CHAIN: LASH, HOOK, BIND, SPIN.",
            "SHE RUNS ON JUDGMENT, FILLED BY HER CENSER BLOWS. CURSED FOES (THE UNHOLY, AND EVERY BOSS) SUFFER MORE FROM HER.",
        ],
    };
    t.iter().map(|s| s.to_string()).collect()
}
